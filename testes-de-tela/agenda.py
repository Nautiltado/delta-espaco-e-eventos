"""Agenda: painel lateral do dia, cadastro rápido (orçamento, sem bloquear a data), data segura, bloqueio com conflito, remoção, vistas e filtros. Conta teste.e2e.adm."""
import os, random, re
from playwright.sync_api import sync_playwright
BASE="http://localhost:3100"; SENHA=os.environ["SENHA_TESTE"]
D=f"2028-{random.randint(1,4):02d}-{random.randint(10,20):02d}"
res=[]
def ok(n,c,d=""): res.append(bool(c)); print("OK  " if c else "FALHA",n,str(d)[:200],flush=True)
with sync_playwright() as p:
    b=p.chromium.launch(executable_path="/usr/bin/google-chrome")
    pg=b.new_context(viewport={"width":1440,"height":900},locale="pt-BR").new_page()
    pg.goto(f"{BASE}/entrar"); pg.fill("#email","teste.e2e.adm@delta.test"); pg.fill("#senha",SENHA); pg.click("button:has-text('Entrar')"); pg.wait_for_url(f"{BASE}/")
    pg.goto(f"{BASE}/agenda?data={D}"); pg.click(f"[data-dia='{D}'] .abrir-dia")
    ok("URL guarda o dia aberto", f"dia={D}" in pg.url, pg.url)
    pg.click(".gaveta-acoes button:has-text('Novo evento')")
    pg.click(".gaveta button:has-text('Novo cliente')")
    pg.fill("#ev-novo-nome","Cliente Agenda (teste)"); pg.fill("#ev-titulo","Festa Agenda (teste)")
    pg.fill("#ev-ini","19:00"); pg.fill("#ev-fim","23:00")
    pg.locator(".gaveta label.opcao",has_text="Espaço menor").locator("input").check()
    pg.fill("#ev-conv","80")
    pg.click(".gaveta button:has-text('Verificar disponibilidade')"); pg.wait_for_selector(".resultado-disp li")
    ok("verificar mostra menor disponível", "disponível" in pg.inner_text(".resultado-disp"), pg.inner_text(".resultado-disp"))
    pg.locator(".gaveta label.opcao",has_text="Segurar a data").locator("input").check()
    pg.click(".gaveta button:has-text('Criar orçamento e segurar a data')")
    pg.wait_for_selector(".gaveta .aviso.ok, .gaveta .aviso.erro",timeout=20000)
    t=pg.inner_text(".gaveta-corpo"); ok("evento rápido cria orçamento e segura a data","data segura" in t and "ORC-" in t, t)
    pg.screenshot(path="/tmp/capturas/fluxo-evento-ok.png")
    pg.wait_for_timeout(1500)
    pg.goto(f"{BASE}/agenda?data={D}&dia={D}"); pg.wait_for_selector(".gaveta")
    ok("abre direto pelo ?dia=", pg.locator(".gaveta").count()==1)
    t=pg.inner_text(".gaveta-corpo")
    ok("cartão do evento no painel", "Festa Agenda (teste)" in t and "Cliente Agenda (teste)" in t and "80" in t, t)
    ok("espaço menor aguardando formalização", "Aguardando formalização" in pg.inner_text("[data-espaco='Espaço menor']"))
    ok("espaço maior disponível", "Disponível" in pg.inner_text("[data-espaco='Espaço maior']"))
    cls=pg.locator(f"[data-dia='{D}'] .ocupacao").first.get_attribute("class")
    ok("chip amarelo (temporário) na célula", "temporario" in cls, cls)
    pg.screenshot(path="/tmp/capturas/fluxo-painel-evento.png")
    # bloqueio em conflito
    pg.click(".gaveta-acoes button:has-text('Bloquear data ou horário')")
    pg.locator(".gaveta label.opcao",has_text="Espaço menor").locator("input").check()
    pg.fill("#b-ini","18:00"); pg.fill("#b-fim","23:30"); pg.fill("#b-mot","Teste conflito (teste)")
    pg.click(".gaveta button:has-text('Verificar conflitos')"); pg.wait_for_selector(".resultado-disp li")
    ok("verificar conflitos aponta a reserva", "ocupado" in pg.inner_html(".resultado-disp"), pg.inner_text(".resultado-disp"))
    pg.click(".gaveta-rodape-form button:has-text('Bloquear')"); pg.wait_for_selector(".gaveta .aviso.erro",timeout=20000)
    ok("bloqueio não passa por cima da reserva", "não pode passar por cima" in pg.inner_text(".gaveta .aviso.erro"), pg.inner_text(".gaveta .aviso.erro"))
    pg.screenshot(path="/tmp/capturas/fluxo-conflito.png")
    # bloqueio ok no maior
    pg.locator(".gaveta label.opcao",has_text="Espaço maior").locator("input").check()
    pg.fill("#b-ini","08:00"); pg.fill("#b-fim","12:00"); pg.fill("#b-mot","Manutenção agenda (teste)"); pg.fill("#b-obs","Troca de lâmpadas")
    pg.click(".gaveta-rodape-form button:has-text('Bloquear')"); pg.wait_for_selector(".gaveta .aviso.ok",timeout=20000)
    ok("bloqueio sem conflito gravado", "Agenda bloqueada" in pg.inner_text(".gaveta .aviso.ok"))
    pg.click(".gaveta button:has-text('Voltar ao dia')"); pg.wait_for_timeout(1500)
    t=pg.inner_text(".gaveta-corpo")
    ok("painel mostra bloqueio com quem e observação", "Manutenção agenda (teste)" in t and "Teste ADM" in t and "Troca de lâmpadas" in t, t)
    pg.click(".gaveta button:has-text('Remover bloqueio')"); pg.click(".gaveta button:has-text('Sim, remover')")
    pg.wait_for_selector(".gaveta .aviso.ok",timeout=20000)
    ok("bloqueio removido pelo painel", "Bloqueio removido" in pg.inner_text(".gaveta .aviso.ok"))
    # evento sem segurar não ocupa
    pg.click(".gaveta-acoes button:has-text('Novo evento')")
    pg.select_option("#ev-cliente", label="Cliente Agenda (teste)")
    pg.fill("#ev-titulo","Negociação Agenda (teste)")
    pg.locator(".gaveta label.opcao",has_text="Espaço maior").locator("input").check()
    pg.click(".gaveta-rodape-form button:has-text('Criar orçamento')"); pg.wait_for_selector(".gaveta .aviso.ok",timeout=20000)
    ok("sem segurar: orçamento, data livre", "continua livre" in pg.inner_text(".gaveta .aviso.ok"))
    pg.wait_for_timeout(1500)
    pg.goto(f"{BASE}/agenda?data={D}&dia={D}"); pg.wait_for_selector(".gaveta")
    ok("espaço maior segue disponível", "Disponível" in pg.inner_text("[data-espaco='Espaço maior']"))
    # externo
    pg.click(".gaveta-acoes button:has-text('Registrar evento externo')")
    pg.select_option("#ev-cliente", label="Cliente Agenda (teste)")
    pg.fill("#ev-titulo","Buffet externo (teste)"); pg.fill("#ev-local","Clube (teste), Bacabal")
    pg.click(".gaveta-rodape-form button:has-text('Criar orçamento')"); pg.wait_for_selector(".gaveta .aviso.ok, .gaveta .aviso.erro",timeout=20000)
    ok("evento externo registrado como orçamento", "evento externo criado" in pg.inner_text(".gaveta-corpo"), pg.inner_text(".gaveta-corpo"))
    # vistas com dados
    for v in ("semana","dia","lista"):
        pg.goto(f"{BASE}/agenda?vista={v}&data={D}"); pg.wait_for_load_state("networkidle")
        ok(f"vista {v} mostra o evento", "Festa Agenda (teste)" in pg.inner_text("main"))
        pg.screenshot(path=f"/tmp/capturas/fluxo-{v}.png", full_page=True)
    pg.goto(f"{BASE}/agenda?vista=mes&data={D}&espaco=externos"); pg.wait_for_selector(".calendario")
    ok("filtro externos esconde reserva do salão", pg.locator(f"[data-dia='{D}'] .ocupacao").count()==0)
    b.close()
print(f"RESULTADO {sum(res)} de {len(res)}")
