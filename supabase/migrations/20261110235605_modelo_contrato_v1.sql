POLÍTICA CONTRATUAL DE CANCELAMENTO, DESISTÊNCIA, REMARCAÇÃO E INADIMPLEMENTO

ANEXO CONTRATUAL — CONDIÇÕES GERAIS DE CONTRATAÇÃO

CLÁUSULA PRIMEIRA — DO OBJETO E DA VINCULAÇÃO CONTRATUAL

1.1. A presente política estabelece as condições aplicáveis à contratação, ao cancelamento, à desistência, à remarcação, ao inadimplemento e à resolução dos contratos celebrados com a DELTA ESPAÇO E EVENTOS, abrangendo locação de espaços, serviços de buffet, alimentação, coffee break, café da manhã, brunch, almoço, jantar, petit four, bandejas rodadas, lanches e demais serviços relacionados à realização de eventos.

1.2. Esta política integra o contrato principal e deverá ser interpretada conjuntamente com a proposta comercial, a ordem de serviço e eventuais aditivos contratuais.

1.3. O CONTRATANTE declara ter recebido e tido oportunidade de examinar previamente esta política, reconhecendo que as condições de pagamento, cancelamento e remarcação constituem elementos essenciais da contratação.

CLÁUSULA SEGUNDA — DA CONFIRMAÇÃO DA RESERVA E DO PAGAMENTO INICIAL

2.1. A disponibilização de orçamento, consulta de disponibilidade, negociação comercial ou envio de proposta não constitui reserva definitiva de qualquer espaço ou data.

2.2. A confirmação definitiva da reserva estará condicionada, cumulativamente:

I – À aprovação formal da proposta comercial;

II – À celebração do contrato pelas partes;

III – Ao efetivo recebimento, pela CONTRATADA, do pagamento inicial correspondente a 50% (cinquenta por cento) do valor total contratado;

IV – À confirmação da disponibilidade do espaço e dos recursos operacionais necessários.

2.3. Até o cumprimento integral das condições acima, a data permanecerá disponível para comercialização, não estando a CONTRATADA obrigada a mantê-la bloqueada em favor do interessado.

2.4. O pagamento inicial de 50% (cinquenta por cento) constitui adiantamento do preço contratado e princípio de execução financeira do negócio, não sendo considerado, isoladamente, multa, arras ou autorização para retenção integral automática em caso de cancelamento.

2.5. Após a confirmação da reserva, a CONTRATADA compromete-se a indisponibilizar o espaço e organizar sua estrutura para a realização do evento, observadas as condições contratadas.

CLÁUSULA TERCEIRA — DAS CONDIÇÕES DE CANCELAMENTO PELO CONTRATANTE

3.1. A desistência imotivada do CONTRATANTE, após a confirmação da reserva, acarretará a incidência de multa compensatória, considerando a antecedência do cancelamento, a indisponibilização da estrutura, o comprometimento da agenda comercial e a mobilização administrativa e operacional da CONTRATADA.

3.2. A multa será calculada mediante aplicação dos seguintes percentuais sobre o valor dos serviços efetivamente cancelados e ainda não executados:

I – Cancelamento com antecedência superior a 120 (cento e vinte) dias: 10% (dez por cento);

II – Cancelamento entre 91 (noventa e um) e 120 (cento e vinte) dias: 15% (quinze por cento);

III – Cancelamento entre 61 (sessenta e um) e 90 (noventa) dias: 20% (vinte por cento);

IV – Cancelamento entre 31 (trinta e um) e 60 (sessenta) dias: 25% (vinte e cinco por cento);

V – Cancelamento entre 8 (oito) e 30 (trinta) dias: 30% (trinta por cento);

VI – Cancelamento com antecedência igual ou inferior a 7 (sete) dias: 35% (trinta e cinco por cento).

3.3. Em caso de cancelamento integral, a base de cálculo corresponderá ao valor total dos serviços contratados e ainda não executados.

3.4. Na hipótese de cancelamento parcial, a penalidade incidirá sobre o valor dos itens efetivamente cancelados, preservando-se as obrigações relativas aos serviços que permanecerem contratados.

3.5. A multa possui natureza compensatória, destinando-se a prefixar os prejuízos ordinariamente relacionados à desistência imotivada, especialmente a indisponibilização comercial da data, a organização da estrutura, o planejamento de pessoal e a preparação operacional.

3.6. Os valores pagos anteriormente serão imputados ao pagamento das obrigações apuradas, inclusive da multa compensatória, devendo eventual saldo excedente ser restituído ao CONTRATANTE.

3.7. Eventual diferença devida pelo CONTRATANTE deverá ser comunicada e fundamentada, respeitados os limites estabelecidos pela legislação aplicável.

CLÁUSULA QUARTA — DA INDENIZAÇÃO SUPLEMENTAR E DOS CUSTOS OPERACIONAIS

4.1. Caso os prejuízos efetivamente suportados pela CONTRATADA ultrapassem o valor da multa compensatória, poderá ser exigida indenização suplementar, desde que expressamente demonstrado o prejuízo excedente, nos termos do artigo 416, parágrafo único, do Código Civil.

4.2. Poderão ser considerados, mediante documentação comprobatória:

I – Aquisição de ingredientes e insumos destinados especificamente ao evento;

II – Produção de alimentos e produtos personalizados;

III – Despesas com fornecedores e serviços terceirizados;

IV – Contratação de garçons, seguranças e auxiliares;

V – Pagamentos não recuperáveis efetuados a fornecedores;

VI – Materiais especiais adquiridos para atendimento da contratação;

VII – Outros compromissos financeiros diretamente relacionados ao evento cancelado.

4.3. A apuração deverá considerar os valores efetivamente suportados, eventuais reembolsos recebidos, despesas evitadas e demais circunstâncias que interfiram no prejuízo.

4.4. A indenização suplementar corresponderá exclusivamente ao prejuízo excedente comprovado em relação ao montante da multa compensatória, vedada qualquer duplicidade de cobrança.

4.5. A CONTRATADA manterá os respectivos comprovantes para fundamentar eventual cobrança adicional.

CLÁUSULA QUINTA — DA REMARCAÇÃO

5.1. A alteração da data constitui solicitação sujeita à análise e à aprovação expressa da CONTRATADA, não configurando direito automático do CONTRATANTE.

5.2. A CONTRATADA poderá, a seu critério comercial e mediante disponibilidade, conceder uma única remarcação da data originalmente contratada.

5.3. A solicitação deverá ser realizada preferencialmente com antecedência mínima de 30 (trinta) dias, sendo que pedidos formulados em prazo inferior poderão ser recusados ou dependerão de negociação específica.

5.4. A eventual remarcação deverá ocorrer, em regra, dentro do prazo máximo de 180 (cento e oitenta) dias da data originalmente prevista, mediante disponibilidade do espaço, da cozinha, dos equipamentos e dos profissionais necessários.

5.5. A nova contratação poderá sofrer atualização dos valores em razão de diferenças de preços, alterações de serviços, quantidade de convidados, data ou condições operacionais.

5.6. Despesas específicas e não recuperáveis já assumidas para a data anterior poderão ser objeto de apuração e ajuste, mediante comprovação e concordância das partes.

5.7. A remarcação somente produzirá efeitos após aprovação formal da CONTRATADA e assinatura de aditivo ou instrumento equivalente.

5.8. A negativa de remarcação, quando inexistir obrigação legal de concedê-la, não afastará a aplicação das regras de cancelamento previstas neste instrumento, ressalvadas as hipóteses de força maior e os direitos legais do consumidor.

CLÁUSULA SEXTA — DA QUANTIDADE DE CONVIDADOS E DOS SERVIÇOS CONTRATADOS

6.1. O CONTRATANTE deverá informar e confirmar a quantidade definitiva de convidados, produtos e serviços com antecedência mínima de 10 (dez) dias da realização do evento, salvo prazo diverso expressamente estipulado na proposta comercial.

6.2. A quantidade definitivamente informada e aceita pela CONTRATADA servirá como referência mínima de planejamento, aquisição de insumos, dimensionamento da equipe e organização da produção.

6.3. Após a confirmação definitiva, eventual redução do número de convidados não implicará redução automática do preço contratado, especialmente quando a CONTRATADA já tiver iniciado aquisições, produção, preparação ou contratação de profissionais.

6.4. Acréscimos de convidados, alimentação, bebidas e serviços dependerão de aprovação da CONTRATADA e disponibilidade operacional, sujeitando-se a cobrança adicional.

6.5. A CONTRATADA não estará obrigada a fornecer quantidades superiores às contratadas sem prévia autorização e adequação financeira.

6.6. O eventual não comparecimento de convidados não dará direito à restituição de valores referentes a quantidades previamente confirmadas, adquiridas, preparadas ou disponibilizadas conforme a contratação.

CLÁUSULA SÉTIMA — DO PAGAMENTO E DO INADIMPLEMENTO

7.1. A condição ordinária de pagamento da DELTA ESPAÇO E EVENTOS será:

I – 50% (cinquenta por cento) no ato da contratação;

II – 50% (cinquenta por cento) restantes até 7 (sete) dias antes da realização do evento.

7.2. A segunda parcela deverá ser quitada integralmente no prazo convencionado, sendo vedado ao CONTRATANTE condicionar seu pagamento à realização futura do evento, salvo disposição expressa em sentido contrário.

7.3. O atraso no pagamento acarretará a constituição em mora do CONTRATANTE, observadas as condições de vencimento e as regras legais aplicáveis.

7.4. Verificada a inadimplência, a CONTRATADA poderá encaminhar notificação ao CONTRATANTE, concedendo prazo de 48 (quarenta e oito) horas para regularização.

7.5. Não ocorrendo a regularização dentro do prazo concedido, a CONTRATADA poderá resolver o contrato por inadimplemento imputável ao CONTRATANTE, mediante comunicação formal.

7.6. Na hipótese de resolução por inadimplemento, será apurada a multa compensatória correspondente à antecedência existente entre a data da resolução e a data prevista para o evento, sem prejuízo da indenização suplementar prevista neste instrumento, quando cabível e comprovada.

7.7. A CONTRATADA poderá suspender preparativos e serviços acessórios ainda não executados enquanto persistir inadimplemento relevante, mediante prévia comunicação, sem prejuízo das providências legais e contratuais cabíveis.

7.8. Contratações realizadas com menos de 7 (sete) dias de antecedência deverão ter o valor integral quitado antes do início da execução, conforme condição específica expressamente apresentada e aceita pelo CONTRATANTE.

7.9. A tolerância quanto a atrasos não representará renúncia aos direitos da CONTRATADA nem alteração definitiva do vencimento.

CLÁUSULA OITAVA — DA AUSÊNCIA DO CONTRATANTE (NO-SHOW)

8.1. O não comparecimento do CONTRATANTE, sem comunicação prévia ou justificativa juridicamente relevante, será tratado como desistência na data do evento.

8.2. Na hipótese, poderá incidir a multa correspondente ao cancelamento com antecedência igual ou inferior a 7 (sete) dias, observada a base de cálculo prevista na Cláusula Terceira.

8.3. Permanecerão devidos os valores relativos à locação disponibilizada e aos serviços efetivamente executados, preparados ou colocados à disposição, conforme o objeto contratado, observada a vedação de cobrança duplicada com a multa compensatória.

8.4. Eventuais prejuízos suplementares deverão ser individualizados e comprovados.

CLÁUSULA NONA — DOS EVENTOS CANCELADOS POR INICIATIVA DA CONTRATADA

9.1. Quando o cancelamento decorrer de descumprimento contratual imputável à CONTRATADA, o CONTRATANTE poderá optar pela remarcação, mediante comum acordo, ou pela resolução do contrato.

9.2. Na hipótese de resolução por responsabilidade da CONTRATADA, serão restituídos os valores recebidos relativos aos serviços não executados, monetariamente atualizados, sem prejuízo da multa compensatória equivalente à prevista para o CONTRATANTE na Cláusula Terceira, calculada sobre o valor dos serviços não executados.

9.3. A presente disposição não afasta a eventual responsabilidade por prejuízos suplementares legalmente cabíveis.

CLÁUSULA DÉCIMA — DO CASO FORTUITO E DA FORÇA MAIOR

10.1. A ocorrência de fato inevitável e alheio à vontade das partes que efetivamente impossibilite a realização do evento deverá ser comunicada imediatamente, acompanhada dos elementos comprobatórios disponíveis.

10.2. As partes deverão priorizar a negociação de nova data ou outra solução consensual que preserve, na medida do possível, a contratação.

10.3. Não sendo possível a continuidade do negócio, serão apuradas as prestações efetivamente realizadas, os valores correspondentes aos serviços não executados e as despesas específicas comprovadamente incorridas, observados o artigo 393 do Código Civil e a legislação consumerista, quando aplicável.

10.4. Não será automaticamente aplicada a multa por desistência imotivada nas hipóteses de impossibilidade juridicamente caracterizada decorrente de caso fortuito ou força maior.

